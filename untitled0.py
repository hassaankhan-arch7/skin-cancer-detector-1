"""### Step 1: Exploratory Data Analysis (EDA) & Dataset Visualization
Let's analyze the extracted directory structure, count the images in each category, and display a pie chart of the dataset distribution.
"""

import os
import glob
import pandas as pd
import matplotlib.pyplot as plt

dataset_dir = '/content/unzipped_data/data'

# Find all image paths
all_images = glob.glob(os.path.join(dataset_dir, '**/*.jpg'), recursive=True)
print(f"Total images found: {len(all_images)}")

# Distinguish classes
class_counts = {}
for img_path in all_images:
    parts = img_path.split(os.sep)
    # Class name is usually the parent directory of the file
    class_name = parts[-2]
    class_counts[class_name] = class_counts.get(class_name, 0) + 1

print("Class distribution:", class_counts)

# Plot a pie chart
plt.figure(figsize=(8, 8))
plt.pie(class_counts.values(), labels=class_counts.keys(), autopct='%1.1f%%', startangle=140, colors=['#4CAF50', '#FF5722'])
plt.title('Dataset Class Distribution')
plt.show()

"""### Step 2: Split and Load Data using Keras Image Generators
We will configure automated split loading for training and validation splits directly from the image directories.
"""

import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Configure image size and training hyperparameters
IMG_SIZE = (128, 128)
BATCH_SIZE = 32

train_datagen = ImageDataGenerator(
    rescale=1.0/255,
    validation_split=0.2, # 20% validation split
    rotation_range=20,
    zoom_range=0.15,
    horizontal_flip=True
)

train_generator = train_datagen.flow_from_directory(
    dataset_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='training',
    seed=42
)

val_generator = train_datagen.flow_from_directory(
    dataset_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='validation',
    seed=42,
    shuffle=False
)

"""### Step 3: Define and Train a Convolutional Neural Network (CNN)
Now, we'll design a standard CNN model with convolutional, pooling, dropout, and dense layers.
"""

from tensorflow.keras import layers, models
from sklearn.utils.class_weight import compute_class_weight
import numpy as np

# Design the CNN model
model = models.Sequential([
    layers.Input(shape=(128, 128, 3)),
    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5),
    layers.Dense(1, activation='sigmoid')
])

model.compile(optimizer='adam',
              loss='binary_crossentropy',
              metrics=['accuracy'])

model.summary()

# Compute class weights to address the dataset imbalance
classes = train_generator.classes
class_weights_array = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(classes),
    y=classes
)
class_weights = dict(enumerate(class_weights_array))
print(f"Calculated Class Weights: {class_weights}")

# Train the model with class weights
history = model.fit(
    train_generator,
    validation_data=val_generator,
    epochs=10,
    class_weight=class_weights
)

"""### Step 4: Model Evaluation and Classification Report
Finally, we will evaluate the trained model on our validation set, generate class predictions, calculate loss/accuracy metrics, and output a comprehensive classification report.
"""

import numpy as np
from sklearn.metrics import classification_report, accuracy_score

# Evaluate basic metrics on validation set
val_loss, val_acc = model.evaluate(val_generator)
print(f"Validation Loss: {val_loss:.4f}")
print(f"Validation Accuracy: {val_acc:.4f}")

# Predict probabilities
val_generator.reset()
predictions = model.predict(val_generator)
y_pred = (predictions > 0.5).astype(int).ravel()
y_true = val_generator.classes

# Print evaluation metrics
print("\n--- Accuracy Score ---")
print(f"{accuracy_score(y_true, y_pred):.4%}")

print("\n--- Classification Report ---")
target_names = list(val_generator.class_indices.keys())
print(classification_report(y_true, y_pred, target_names=target_names))

"""### Step 5: Generate and Compare Predictions on Test Data
We will set up a dedicated data generator for the test subdirectory to predict classes on unseen test images, then display a comparison table of actual vs. predicted labels.
"""

import numpy as np
import pandas as pd
import os

test_dir = os.path.join(dataset_dir, 'test')

# Configure test generator (no shuffle to match labels with predictions accurately)
test_datagen = ImageDataGenerator(rescale=1.0/255)

test_generator = test_datagen.flow_from_directory(
    test_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=False
)

# Generate model predictions
predictions = model.predict(test_generator)
predicted_classes = (predictions > 0.5).astype(int).ravel()
actual_classes = test_generator.classes

# Map numerical indices back to class labels
class_labels = {v: k for k, v in test_generator.class_indices.items()}
actual_labels = [class_labels[idx] for idx in actual_classes]
predicted_labels = [class_labels[idx] for idx in predicted_classes]

# Combine into a pandas DataFrame
results_df = pd.DataFrame({
    'File Path': test_generator.filepaths,
    'Actual Label': actual_labels,
    'Predicted Label': predicted_labels,
    'Probability (Malignant)': predictions.ravel()
})

# Remove path prefix for cleaner presentation
results_df['File Name'] = results_df['File Path'].apply(lambda x: os.path.basename(x))
results_df = results_df[['File Name', 'Actual Label', 'Predicted Label', 'Probability (Malignant)']]

# Display overall stats and a preview of predictions
print("--- Test Data Predictions Overview ---")
display(results_df.head(20))

# Calculate exact test accuracy
test_acc = np.mean(predicted_classes == actual_classes)
print(f"\nTest Set Accuracy: {test_acc:.2%}")

"""### Step 6: Plot Confusion Matrix
Now, let's plot a confusion matrix using `seaborn` and `sklearn` to visually inspect how many true benign and malignant cases are correctly classified by our balanced model.
"""

import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import confusion_matrix

# Compute confusion matrix
cm = confusion_matrix(y_true, y_pred)

# Plot configuration
plt.figure(figsize=(6, 5))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=target_names, yticklabels=target_names)
plt.title('Confusion Matrix on Validation Set')
plt.ylabel('Actual Class')
plt.xlabel('Predicted Class')
plt.tight_layout()
plt.show()

"""### Step 7: Save the Trained Model
We will save our trained balanced model structure and weights to a `.keras` file in our directory so that it can be loaded later for prediction or deployment.
"""

# Save the model in native Keras format
model_path = '/content/skin_cancer_detector.keras'
model.save(model_path)
print(f"Model successfully saved to {model_path}!")